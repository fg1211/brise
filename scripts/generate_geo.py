#!/usr/bin/env python3
"""Generate the lightweight Germany geometry used by the Brise desktop UI.

Source: Natural Earth 1:50m cultural vectors (public domain).
Only the German country outline and state boundaries are extracted and
simplified for the offline desktop application.
"""
from __future__ import annotations

import json
import math
import urllib.request
from pathlib import Path

BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/"
COUNTRY_URL = BASE + "ne_50m_admin_0_countries.geojson"
STATES_URL = BASE + "ne_10m_admin_1_states_provinces.geojson"
OUT = Path(__file__).resolve().parents[1] / "ui" / "js" / "germany-geo.js"


def fetch(url: str) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": "brise-wetter/1.0"})
    with urllib.request.urlopen(req, timeout=120) as response:
        return json.load(response)


def perpendicular_distance(point, start, end):
    x, y = point
    x1, y1 = start
    x2, y2 = end
    dx, dy = x2 - x1, y2 - y1
    if dx == 0 and dy == 0:
        return math.hypot(x - x1, y - y1)
    t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - (x1 + t * dx), y - (y1 + t * dy))


def simplify(points, tolerance):
    if len(points) <= 3:
        return points
    # Iterative Ramer-Douglas-Peucker to avoid recursion limits.
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        first, last = stack.pop()
        max_dist, index = 0.0, None
        for i in range(first + 1, last):
            dist = perpendicular_distance(points[i], points[first], points[last])
            if dist > max_dist:
                max_dist, index = dist, i
        if index is not None and max_dist > tolerance:
            keep[index] = True
            stack.append((first, index))
            stack.append((index, last))
    return [p for p, k in zip(points, keep) if k]


def round_points(points, tolerance=0.0035):
    result = []
    for lon, lat in simplify(points, tolerance):
        item = [round(lon, 4), round(lat, 4)]
        if not result or result[-1] != item:
            result.append(item)
    return result


def rings_from_geometry(geometry):
    if geometry["type"] == "Polygon":
        return [geometry["coordinates"][0]]
    if geometry["type"] == "MultiPolygon":
        return [poly[0] for poly in geometry["coordinates"]]
    return []


def main():
    countries = fetch(COUNTRY_URL)
    country = next(
        f
        for f in countries["features"]
        if f["properties"].get("ADM0_A3") == "DEU"
        or f["properties"].get("ADMIN") == "Germany"
    )

    countries_filtered = []
    for ring in rings_from_geometry(country["geometry"]):
        simple = round_points(ring, 0.004)
        if len(simple) >= 4:
            # Skip tiny islands, but keep Rügen, Usedom, Fehmarn and Sylt.
            lons = [p[0] for p in simple]
            lats = [p[1] for p in simple]
            if (max(lons) - min(lons)) * (max(lats) - min(lats)) > 0.006:
                countries_filtered.append(simple)

    states_data = fetch(STATES_URL)
    states = []
    for feature in states_data["features"]:
        props = feature["properties"]
        if not (
            props.get("adm0_a3") == "DEU"
            or props.get("ADM0_A3") == "DEU"
            or props.get("admin") == "Germany"
        ):
            continue
        all_rings = []
        for ring in rings_from_geometry(feature["geometry"]):
            simple = round_points(ring, 0.011)
            if len(simple) >= 4:
                all_rings.append(simple)
        if all_rings:
            states.append(
                {
                    "name": props.get("name_de") or props.get("name") or "",
                    "rings": all_rings,
                }
            )

    out = {
        "outline": countries_filtered,
        "states": states,
        "bounds": [5.5, 47.1, 15.4, 55.2],
        "source": "Natural Earth 1:10m/1:50m (public domain)",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/generate_geo.py — Natural Earth 1:50m (public domain).\n"
        "export const GERMANY_GEO = "
        + json.dumps(out, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    print(
        f"Wrote {OUT} ({OUT.stat().st_size / 1024:.1f} KiB), "
        f"{len(countries_filtered)} outline rings, {len(states)} states"
    )


if __name__ == "__main__":
    main()
